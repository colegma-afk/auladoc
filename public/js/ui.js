// ---------- Toast ----------
UI.toast = (msg, type = 'success') => {
  const icons = { success: UI.ICONS.checkCircle, error: UI.ICONS.alert, info: UI.ICONS.info };
  const el = document.createElement('div');
  el.className = `toast ${type}`;
  el.innerHTML = icons[type] + `<span>${msg}</span>`;
  document.getElementById('toasts').appendChild(el);
  setTimeout(() => { el.style.opacity = '0'; el.style.transition = 'opacity .3s'; setTimeout(() => el.remove(), 320); }, 3400);
};

// ---------- Modal ----------
UI.openModal = (title, bodyHtml, footHtml, opts = {}) => {
  const overlay = document.getElementById('modalOverlay');
  overlay.innerHTML = `
    <div class="modal ${opts.lg ? 'modal-lg' : ''}">
      <div class="modal-head">
        <h3>${title}</h3>
        <button class="modal-x" data-close><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round"><path d="M18 6 6 18M6 6l12 12"/></svg></button>
      </div>
      <div class="modal-body">${bodyHtml}</div>
      ${footHtml ? `<div class="modal-foot">${footHtml}</div>` : ''}
    </div>`;
  overlay.classList.add('open');
  overlay.querySelector('[data-close]').addEventListener('click', UI.closeModal);
  overlay.addEventListener('mousedown', e => { if (e.target === overlay) UI.closeModal(); });
  document.addEventListener('keydown', UI._escHandler = e => { if (e.key === 'Escape') UI.closeModal(); });
  return overlay;
};
UI.closeModal = () => {
  const overlay = document.getElementById('modalOverlay');
  overlay.classList.remove('open');
  overlay.innerHTML = '';
  if (UI._escHandler) document.removeEventListener('keydown', UI._escHandler);
};

