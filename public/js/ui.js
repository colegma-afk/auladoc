// ---------- Tarjeta de curso (reutilizable) ----------
UI.courseCard = (c) => {
  const lessons = c.modules ? c.modules.reduce((n, m) => n + m.lessons.length, 0) : c.totalLessons || 0;
  const btn = c.enrolled
    ? (c.progress.pct >= 100
      ? `<a class="btn btn-ghost btn-sm" href="#/curso/${c.id}">${UI.ICONS.checkCircle} Ver curso</a>`
      : `<a class="btn btn-primary btn-sm" href="#/curso/${c.id}">${UI.ICONS.play} Continuar · ${c.progress.pct}%</a>`)
    : `<a class="btn btn-ghost btn-sm" href="#/curso/${c.id}">Ver detalles</a>`;
  return `
  <div class="card course-card card-hover">
    <a class="cover" href="#/curso/${c.id}">
      <img src="${c.cover}" alt="${c.title}" loading="lazy">
      <span class="chip">${c.category}</span>
      <span class="dur">${UI.ICONS.clock} ${c.hours} h</span>
    </a>
    <div class="cc-body">
      <a href="#/curso/${c.id}" style="color:inherit"><h3 class="cc-title">${c.title}</h3></a>
      <div class="cc-meta">
        <span>${UI.ICONS.video} ${lessons} ${Domain.plural(lessons, 'lección', 'lecciones')}</span>
        <span>${UI.ICONS.grad} ${c.level}</span>
        <span>${UI.ICONS.users} ${c.enrolledCount} inscritos</span>
      </div>
      ${c.enrolled ? `<div>${UI.progressBar(c.progress.pct)}<div style="font-size:12px;color:var(--muted);margin-top:5px">${c.progress.pct}% completado</div></div>` : ''}
      <div class="cc-foot">${btn}</div>
    </div>
  </div>`;
};

